"""Phase 4 Task 5 — exports the CURRENT role -> permission matrix (read
from the live database, not re-derived from migration history) to
docs/ROLE_MATRIX.md for owner review."""
from __future__ import annotations

from pathlib import Path

from django.core.management.base import BaseCommand

from apps.accounts.models import Permission, Role, RolePermission

REPO_ROOT = Path(__file__).resolve().parents[5]  # backend/apps/accounts/management/commands/ -> repo root


class Command(BaseCommand):
    help = 'Exports the current role -> permission matrix to docs/ROLE_MATRIX.md.'

    def handle(self, *args, **options):
        roles = list(Role.objects.filter(is_active=True).order_by('name'))
        permissions = list(Permission.objects.filter(is_deprecated=False).order_by('module', 'action'))
        grants = set(RolePermission.objects.values_list('role_id', 'permission_id'))

        lines = [
            '# Role -> Permission Matrix (generated, not hand-maintained)',
            '',
            f'Generated by `export_role_matrix` from the live database — {len(roles)} active roles, '
            f'{len(permissions)} non-deprecated permissions. Regenerate after any role/permission change; '
            'do not hand-edit this file.',
            '',
            '| Permission | ' + ' | '.join(r.display_name for r in roles) + ' |',
            '|---|' + '---|' * len(roles),
        ]
        for permission in permissions:
            row = [permission.codename]
            for role in roles:
                granted = role.is_full_access or (role.id, permission.id) in grants
                row.append('✅' if granted else '')
            lines.append('| ' + ' | '.join(row) + ' |')

        lines += [
            '',
            '## Role attributes',
            '',
            '| Role | is_full_access | is_default_employee_role | exclude_from_payroll | exclude_from_headcount | is_assignable |',
            '|---|---|---|---|---|---|',
        ]
        for role in roles:
            lines.append(
                f'| {role.display_name} | {"✅" if role.is_full_access else ""} | {"✅" if role.is_default_employee_role else ""} | '
                f'{"✅" if role.exclude_from_payroll else ""} | {"✅" if role.exclude_from_headcount else ""} | {"✅" if role.is_assignable else ""} |'
            )

        output_path = REPO_ROOT / 'docs' / 'ROLE_MATRIX.md'
        output_path.write_text('\n'.join(lines) + '\n', encoding='utf-8')
        self.stdout.write(self.style.SUCCESS(f'Wrote {output_path} ({len(roles)} roles, {len(permissions)} permissions).'))
